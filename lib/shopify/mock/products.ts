const BRL = "BRL";

function realProduct(args: {
  handle: string;
  title: string;
  description: string;
  price: string;
  tags: string[];
  imagePrimary: string;
  imageAlt: string;
  optionName: string;
  optionValues: string[];
  variants: Array<{ title: string; available: boolean }>;
}): ShopifyProduct {
  return {
    id: `gid://mock/Product/${args.handle}`,
    handle: args.handle,
    title: args.title,
    description: args.description,
    descriptionHtml: `<p>${args.description}</p>`,
    featuredImage: {
      url: args.imagePrimary,
      altText: args.title,
      width: 1200,
      height: 1200,
    },
    images: [
      { url: args.imagePrimary, altText: args.title, width: 1200, height: 1200 },
      { url: args.imageAlt, altText: `${args.title} alt`, width: 1200, height: 1200 },
    ],
    priceRange: {
      minVariantPrice: { amount: args.price, currencyCode: BRL },
      maxVariantPrice: { amount: args.price, currencyCode: BRL },
    },
    options: [{ name: args.optionName, values: args.optionValues }],
    variants: args.variants.map((v, i) => ({
      id: `gid://mock/Product/${args.handle}-variant-${i}`,
      title: v.title,
      availableForSale: v.available,
      selectedOptions: [{ name: args.optionName, value: v.title }],
      price: { amount: args.price, currencyCode: BRL },
      image: null,
    })),
    tags: args.tags,
  };
}

